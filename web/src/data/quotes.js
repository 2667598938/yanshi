// 按日期取一条稳定的金句（同一天不变）
export function quoteOfDay(date = new Date()) {
  const dayIndex =
    date.getFullYear() * 372 + (date.getMonth() + 1) * 31 + date.getDate()
  return QUOTES[dayIndex % QUOTES.length]
}
